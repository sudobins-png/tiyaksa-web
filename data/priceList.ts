// берём «обычную» (зачёркнутую у них) цену как единственную цену сейчас, а
// сниженную сохраняем в promoPrice — включим её и UI зачёркивания, когда
// появится собственная акция. Клининг — отдельный источник, без акции:
// https://cleanline-spb.ru/klining-tseny-price-list/#private
export interface PriceItem {
  name: string;
  unit: string;
  /** Текущая цена — «зачёркнутая колонка» источника, сейчас показывается как единственная цена. */
  price?: number;
  /** Цена по акции — механизм зачёркивания пока скрыт в UI, но данные уже здесь. */
  promoPrice?: number;
  approxFrom?: boolean;
  /** Подраздел внутри категории (группировка строк в таблице /price). */
  section?: string;
  /** Показывается в тизере на главной — короткая выборка из полного списка. */
  teaser?: boolean;
}

