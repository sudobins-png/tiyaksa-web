// Источник цен: https://www.prorabneva.ru/price (по указанию владельца — реальный
// прайс-лист референса, не мокап). У них на момент выгрузки была акция -11% до
// 6 сентября: сайт показывал «обычную» цену зачёркнутой рядом со сниженной. Мы
// берём «обычную» (зачёркнутую у них) цену как единственную цену сейчас, а
// сниженную сохраняем в promoPrice — включим её и UI зачёркивания, когда
// появится собственная акция.
export interface PriceItem {
  name: string;
  unit: string;
  /** Текущая цена — «зачёркнутая колонка» источника, сейчас показывается как единственная цена. */
  price?: number;
  /** Цена по акции — механизм зачёркивания пока скрыт в UI, но данные уже здесь. */
  promoPrice?: number;
  approxFrom?: boolean;
}

export interface PriceCategory {
  slug: string;
  name: string;
  items: PriceItem[];
}

